import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, describe, expect, test } from 'vitest';

import { diffSnapshots, takeSnapshot } from '../../src/write-scope/snapshot.js';
import { cleanupRunStateTest } from '../support/run-state.js';
import { writeScopeFixture, type WriteScopeFixture } from '../support/write-scope.js';

afterEach(cleanupRunStateTest);

/** Snapshots before and after the scenario, and returns the diff between the two. */
async function diffAround(scope: WriteScopeFixture, scenario: string, snapshotIgnore: string[] = []) {
  const options = { env: scope.env, cwd: scope.worktree, snapshotIgnore, tempDir: scope.scratch };
  const before = takeSnapshot(options);
  await scope.play(scenario);
  const after = takeSnapshot(options);
  return diffSnapshots({ env: scope.env, cwd: scope.worktree, before, after });
}

describe('the post-step diff compares two snapshots', () => {
  test('a file deleted in the step appears in the post-step diff', async () => {
    const scope = writeScopeFixture();
    writeFileSync(join(scope.worktree, 'notes.txt'), 'untracked before the step\n');

    const changes = await diffAround(scope, 'scope-delete');

    // Both a tracked file and an untracked file are gone from disk, and the diff lists them by path.
    expect(existsSync(join(scope.worktree, 'README.md'))).toBe(false);
    expect(existsSync(join(scope.worktree, 'notes.txt'))).toBe(false);
    expect(changes).toEqual([
      { path: 'README.md', kind: 'deleted' },
      { path: 'notes.txt', kind: 'deleted' },
    ]);
  });

  test('a file reverted to its pre-step contents appears in the post-step diff', async () => {
    const scope = writeScopeFixture();
    // The step starts from an edited file; the scenario writes the committed contents back.
    writeFileSync(join(scope.worktree, 'src/app.ts'), 'export const app = 2; // edited before the step\n');

    const changes = await diffAround(scope, 'scope-revert');

    expect(changes).toEqual([{ path: 'src/app.ts', kind: 'modified' }]);
  });

  test('a change under snapshot_ignore does not appear in the post-step diff', async () => {
    const scope = writeScopeFixture();
    mkdirSync(join(scope.worktree, 'dist'));
    writeFileSync(join(scope.worktree, 'dist/out.js'), 'old output\n');

    const changes = await diffAround(scope, 'scope-ignored', ['dist/**']);

    // The step rewrote dist/out.js and added src/kept.txt; only the second one is outside the ignore list.
    expect(readFileSync(join(scope.worktree, 'dist/out.js'), 'utf8')).toBe('generated by the fake worker\n');
    expect(changes).toEqual([{ path: 'src/kept.txt', kind: 'added' }]);
  });
});
