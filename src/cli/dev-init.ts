import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { stringify } from 'yaml';

import { runDevInit } from '../dev/dev-init.js';
import { resolveFactoryHome } from '../dev/home.js';
import { FactoryError, refused } from '../platform/errors.js';
import { resolveFactoryPaths } from '../platform/paths.js';
import { SAMPLE_TAGS, unpackTodoSandbox } from '../sandbox/todo-sandbox.js';
import type { CommandDef } from './router.js';

const KNOWN_TAGS = SAMPLE_TAGS.join(', ');
const REPO_FILE = 'todo-app.yaml';
const MAKE_HOME_NEXT = 'Run `factory dev-init <throwaway-folder>`, then set FACTORY_HOME to that folder.';

/**
 * The per-repo config of the sample app: matched by absolute path (it has no remote), gates as the sample's npm
 * scripts. Written here, not in src/sandbox, which holds no package-manager commands. Nothing runs the install.
 */
const repoConfigYaml = (sandboxPath: string): string =>
  [
    '# Generated by factory dev-init --sample. Rewritten on every run.',
    stringify({
      match: { path: sandboxPath },
      base_branch: 'main',
      package_manager: 'npm',
      install: 'npm ci',
      gates: { lint: 'npm run lint', typecheck: 'npm run typecheck', test: 'npm test' },
    }),
  ].join('\n');

/** The throwaway home from FACTORY_HOME. Plain errors from the dev-home rules become refusals (exit 2). */
export function throwawayHome(env: NodeJS.ProcessEnv, command = 'dev-init --sample'): string {
  if (!env.FACTORY_HOME) {
    throw refused({
      code: 'dev_home_required',
      message: `FACTORY_HOME is not set. ${command} only works in a throwaway factory home.`,
      where: 'FACTORY_HOME',
      next: MAKE_HOME_NEXT,
    });
  }
  resolveFactoryPaths(env); // refuses a home or cache inside Documents, Desktop or Downloads (protected_folder)
  try {
    return resolveFactoryHome(env);
  } catch (error) {
    if (error instanceof FactoryError) throw error;
    throw refused({
      code: 'dev_home_invalid',
      message: error instanceof Error ? error.message : String(error),
      where: 'FACTORY_HOME',
      next: MAKE_HOME_NEXT,
    });
  }
}

/**
 * `factory dev-init [path]`: with a path, creates the throwaway home and starter config.yaml (no sample).
 * `factory dev-init --sample <tag>`: unpacks the checked-in to-do sample under an existing throwaway home.
 * Path and `--sample` together are refused. Starts no agent and touches no run, worktree or baseline report.
 */
export const devInitCommand: CommandDef = {
  description: 'Dev only: create a throwaway factory home, or unpack the sample into one.',
  skipGitCheck: true,
  optionalPositionals: ['path'],
  options: { sample: { type: 'string' } },
  run: ({ values, positionals }) => {
    const env = process.env;
    const tag = typeof values.sample === 'string' ? values.sample : undefined;
    const path = positionals[0];

    if (path !== undefined && tag !== undefined) {
      throw refused({
        code: 'invalid_usage',
        message: 'factory dev-init takes a path or --sample, not both.',
        where: 'dev-init',
        next: 'Run `factory dev-init <path>` to make the home, or `factory dev-init --sample todo-v0` after FACTORY_HOME is set.',
      });
    }

    if (path !== undefined) {
      try {
        const configPath = runDevInit(path, env);
        return {
          message: `Created ${configPath}`,
          data: { schema_version: 1, config_path: configPath },
        };
      } catch (error) {
        if (error instanceof FactoryError) throw error;
        throw refused({
          code: 'dev_home_invalid',
          message: error instanceof Error ? error.message : String(error),
          where: path,
          next: MAKE_HOME_NEXT,
        });
      }
    }

    if (tag === undefined) {
      throw refused({
        code: 'sample_required',
        message: 'dev-init needs a path or --sample <tag>.',
        where: 'dev-init',
        next: `Run \`factory dev-init <path>\` to make a throwaway home, or \`factory dev-init --sample todo-v0\`. Known samples: ${KNOWN_TAGS}.`,
      });
    }
    if (!SAMPLE_TAGS.includes(tag)) {
      throw refused({
        code: 'sample_unknown',
        message: `Unknown sample "${tag}".`,
        where: `--sample ${tag}`,
        next: `Use one of: ${KNOWN_TAGS}.`,
      });
    }

    const home = throwawayHome(env);
    const { reposDir } = resolveFactoryPaths(env);
    const { path: sandboxPath } = unpackTodoSandbox({ env, sample: tag });

    mkdirSync(reposDir, { recursive: true });
    const repoFile = join(reposDir, REPO_FILE);
    writeFileSync(repoFile, repoConfigYaml(sandboxPath), 'utf8');
    return {
      message: `Sample ${tag} is ready at ${sandboxPath}.\nWrote ${repoFile} (match.path is the sample path) in ${home}.`,
      data: { schema_version: 1, sample: tag, sandbox_path: sandboxPath, repo_config: repoFile },
    };
  },
};
